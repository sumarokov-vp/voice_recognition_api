"""Контракт цели выката — то, что нужно точке входа `deploy-prod.py`.

Точка входа одинаково обращается с обеими целями: печатает шапку по путям, которые цель
объявила выкатываемыми, и дальше либо просит план (`--dry-run`), либо запускает выкат. Всё
остальное — docker там или launchd, сборка образа или `uv pip install` — знает только сама
цель.
"""

from __future__ import annotations

from typing import Protocol


class IDeployTarget(Protocol):
    @property
    def name(self) -> str:
        """Как цель называется в аргументе `--target`."""

    @property
    def summary(self) -> str:
        """Одна строка для шапки: куда и каким способом едет выкат."""

    @property
    def deployed_paths(self) -> tuple[str, ...]:
        """Пути рабочей копии, которые уезжают на эту цель."""

    def print_plan(self) -> None:
        """План выката без единого обращения к машине (`--dry-run`)."""

    def run(self) -> None:
        """Выкат целиком: префлайт, доставка, перезапуск, проверка."""

    def failure_hint(self) -> str:
        """Что осталось на машине после падения и что с этим делать.

        Спрашивается точкой входа при любой ошибке. Ответ зависит от стадии: до доставки
        исходников на машине не изменилось ничего, после — лежит новый код.
        """
